"""Sn00py Bl0ck3r: offline security triage with optional Sushi AI explanations.

User-supplied URLs are never visited; uploaded files and archives are never
executed or uploaded. Only bounded, rule-derived findings are sent to Sushi AI
when the user explicitly presses an AI explanation button in live mode.
"""

import csv
import hashlib
import io
import sqlite3

import streamlit as st

from core.ai_analyzer import analyze_with_ai
from core.database import count_scans, get_recent_scans, save_scan
from scanners.email_scanner import scan_email
from scanners.file_scanner import MAX_FILE_SIZE, scan_file
from scanners.qr_scanner import MAX_QR_IMAGE_BYTES, decode_qr
from scanners.url_scanner import scan_url

st.set_page_config(page_title="Sn00py Bl0ck3r", layout="wide")
st.title("Sn00py Bl0ck3r")
st.subheader("AI-Assisted Cybersecurity Threat Analyzer")
st.write("Review URLs, QR codes, pasted emails, and files using explainable, local security checks.")
st.warning(
    "Scores identify suspicious indicators, not verified threats or probabilities. "
    "No scanner fetches unknown URLs or executes uploaded files."
)


def _state(*keys):
    for key in keys:
        if key not in st.session_state:
            st.session_state[key] = None


def _record(scan_type, result):
    """Save exactly once per Scan button press, not per Streamlit rerun."""
    if result["risk"] != "Invalid":
        try:
            save_scan(scan_type, result)
        except (sqlite3.Error, OSError, ValueError):
            st.warning("Scan worked, but the local history record could not be saved.")


def _render_result(scan_type, result, ai_state, button_key):
    """One shared view for all scanners, preserving existing AI behavior."""
    if result["risk"] == "Invalid":
        st.warning("; ".join(result["findings"]))
        return

    st.subheader("Scan Results")
    c1, c2 = st.columns(2)
    c1.metric("Risk Score", f"{result['score']}/100")
    c2.metric("Risk Level", result["risk"])
    st.progress(result["score"] / 100)

    if scan_type == "File":
        st.subheader("Local File Details")
        st.text(f"Filename: {result['filename']}")
        st.text(f"Size: {result['size_bytes']:,} bytes")
        st.text(f"Signature: {result['file_type']}")
        st.write("**SHA-256 (calculated locally):**")
        st.code(result["sha256"])

    st.subheader("Security Findings")
    for finding in result["findings"]:
        st.write(f"- {finding}")

    if result["risk"] in ("High", "Critical"):
        st.error("Elevated risk indicators detected. Verify the source before interacting with this item.")
    elif result["risk"] == "Medium":
        st.warning("Some characteristics warrant further verification.")
    elif result["score"] > 0:
        st.info(
            "Some risk indicators were detected, but the overall heuristic score is Low. "
            "Review the findings; this is not proof of safety."
        )
    else:
        st.success("No elevated indicators found by these limited checks; this is not proof of safety.")

    st.divider()
    st.subheader("AI Security Explanation")
    st.caption(
        "Optional Sushi AI commentary. Only scan type, score, classification, and bounded findings "
        "are supplied to AI—not original emails, complete URLs, QR images, files, or file hashes. "
        "AI does not assign the numerical score."
    )
    if st.button(f"Generate {scan_type} AI Explanation", key=button_key):
        with st.spinner("Generating explanation..."):
            st.session_state[ai_state] = analyze_with_ai(
                scan_type=scan_type,
                score=result["score"],
                risk=result["risk"],
                findings=result["findings"],
            )

    ai_result = st.session_state[ai_state]
    if ai_result is not None:
        if ai_result["success"]:
            if ai_result["explanation"].startswith("[OFFLINE TEST"):
                st.info("Offline demonstration: this explanation was NOT generated by Sushi AI.")
            st.markdown(ai_result["explanation"])
        else:
            st.warning(ai_result["error"])


def _safe_csv(value):
    """Protect spreadsheet programs from formula injection in exported cells."""
    s = str(value).replace("\r", " ").replace("\n", " ")
    if s.lstrip().startswith(("=", "+", "-", "@")):
        return "'" + s
    return s


def _history_csv(rows):
    out = io.StringIO()
    writer = csv.writer(out)
    writer.writerow(["ID", "Timestamp UTC", "Scanner", "Score", "Risk", "Findings"])
    for record in rows:
        writer.writerow([
            record["id"], record["timestamp"], record["scan_type"],
            record["score"], record["risk"],
            _safe_csv("; ".join(record["findings"])),
        ])
    return out.getvalue().encode("utf-8-sig")


tab1, tab2, tab3, tab4, tab5 = st.tabs([
    "URL Scanner", "QR Code Scanner", "Email Scanner", "File Scanner", "Scan History"
])

# -----------------------------------------------------------------------------
# URL SCANNER
# -----------------------------------------------------------------------------
with tab1:
    st.header("URL Security Analysis")
    st.caption("Local URL heuristics only: URLs are never visited, resolved, or submitted elsewhere.")
    url = st.text_input("Enter an HTTP(S) URL:", placeholder="https://example.com", key="url_input")
    _state("url_result", "url_scanned_input", "url_ai_result")
    if st.button("Scan URL", key="scan_url_btn"):
        st.session_state.url_ai_result = None
        result = scan_url(url)
        st.session_state.url_result = result
        st.session_state.url_scanned_input = url
        _record("URL", result)
    if st.session_state.url_result is not None and url == st.session_state.url_scanned_input:
        _render_result("URL", st.session_state.url_result, "url_ai_result", "url_ai_btn")

# -----------------------------------------------------------------------------
# QR SCANNER
# -----------------------------------------------------------------------------
with tab2:
    st.header("QR Code Security Analysis")
    st.caption("Decode an image locally and inspect HTTP(S) links without opening them.")
    qr_upload = st.file_uploader("Upload a QR image", type=["png", "jpg", "jpeg"], key="qr_upload")
    _state("qr_result", "qr_content", "qr_id", "qr_error", "qr_ai_result")
    if qr_upload is not None:
        if qr_upload.size > MAX_QR_IMAGE_BYTES:
            st.error("QR image exceeds the 8 MiB limit.")
        else:
            qr_data = qr_upload.getvalue()
            qr_id = hashlib.sha256(qr_data).hexdigest()
            st.image(qr_upload, caption="Uploaded QR image", width=250)
            if st.button("Scan QR Code", key="scan_qr_btn"):
                st.session_state.qr_result = None
                st.session_state.qr_content = None
                st.session_state.qr_error = None
                st.session_state.qr_ai_result = None
                st.session_state.qr_id = qr_id
                decoded = decode_qr(qr_data)
                if not decoded["success"]:
                    st.session_state.qr_error = decoded["error"]
                else:
                    st.session_state.qr_content = decoded["content"]
                    if decoded["content"].lower().startswith(("http://", "https://")):
                        result = scan_url(decoded["content"])
                        st.session_state.qr_result = result
                        _record("QR Code", result)
                    else:
                        st.session_state.qr_error = (
                            "The QR code contains non-URL text; it was decoded but cannot receive a URL risk score."
                        )
            if qr_id == st.session_state.qr_id:
                if st.session_state.qr_content is not None:
                    st.success("QR code decoded successfully.")
                    st.write("**Decoded content (never automatically opened):**")
                    st.code(st.session_state.qr_content)
                if st.session_state.qr_error:
                    st.info(st.session_state.qr_error)
                if st.session_state.qr_result is not None:
                    _render_result("QR Code", st.session_state.qr_result, "qr_ai_result", "qr_ai_btn")

# -----------------------------------------------------------------------------
# EMAIL SCANNER
# -----------------------------------------------------------------------------
with tab3:
    st.header("Email Phishing Analysis")
    st.caption(
        "Pasted text, optional headers, HTML-link mismatches, attachment names, and embedded "
        "HTTP(S) links are checked without connecting to mail servers or opening links. "
        "Pasted authentication headers are not independently verified."
    )
    email_text = st.text_area("Paste email body and optional headers:", height=240, key="email_input")
    _state("email_result", "email_scanned_input", "email_ai_result")
    if st.button("Scan Email", key="scan_email_btn"):
        st.session_state.email_ai_result = None
        result = scan_email(email_text)
        st.session_state.email_result = result
        st.session_state.email_scanned_input = email_text
        _record("Email", result)
    if st.session_state.email_result is not None and email_text == st.session_state.email_scanned_input:
        _render_result("Email", st.session_state.email_result, "email_ai_result", "email_ai_btn")

# -----------------------------------------------------------------------------
# FILE SCANNER
# -----------------------------------------------------------------------------
with tab4:
    st.header("File Security Analysis")
    st.caption(
        "Local, static-only inspection: SHA-256, file signatures, extension mismatch, PDF action "
        "markers, and ZIP entry metadata. No file execution, decompression, or external file upload. "
        "Maximum 15 MiB. Files can be selected from local or USB drives."
    )
    file_upload = st.file_uploader("Choose a file to inspect", key="file_upload")
    _state("file_result", "file_id", "file_ai_result")
    if file_upload is not None:
        if file_upload.size > MAX_FILE_SIZE:
            st.error("File exceeds the 15 MiB static scan limit.")
        else:
            file_data = file_upload.getvalue()
            current_file_id = (file_upload.name, hashlib.sha256(file_data).hexdigest())
            if st.button("Scan File", key="scan_file_btn"):
                st.session_state.file_ai_result = None
                result = scan_file(file_upload.name, file_data)
                st.session_state.file_result = result
                st.session_state.file_id = current_file_id
                _record("File", result)
            if st.session_state.file_result is not None and st.session_state.file_id == current_file_id:
                _render_result("File", st.session_state.file_result, "file_ai_result", "file_ai_btn")

# -----------------------------------------------------------------------------
# LOCAL SCAN HISTORY DASHBOARD
# -----------------------------------------------------------------------------
with tab5:
    st.header("Scan History Dashboard")
    st.write("Browse your locally stored security assessments. Database records stay on this computer.")
    st.caption(
        "Only UTC timestamp, scan type, score, risk level, and short findings are stored. "
        "Original URLs, emails, uploaded files, QR images, file hashes, and API keys are excluded."
    )
    try:
        scans = get_recent_scans(limit=500)
        total = count_scans()
    except (sqlite3.Error, OSError, ValueError):
        st.error("Local scan history cannot be opened. The other scanners can still run.")
        scans = []
        total = 0
    c1, c2, c3 = st.columns(3)
    c1.metric("Total Saved Scans", total)
    c2.metric("Recently Retrieved", len(scans))
    c3.metric("High / Critical (retrieved)", sum(s["risk"] in ("High", "Critical") for s in scans))

    scan_filter = st.selectbox(
        "Filter by scanner", ["All", "URL", "QR Code", "Email", "File"], key="history_type_filter"
    )
    risk_filter = st.selectbox(
        "Filter by risk", ["All", "Low", "Medium", "High", "Critical"], key="history_risk_filter"
    )
    filtered = [
        item for item in scans
        if (scan_filter == "All" or item["scan_type"] == scan_filter)
        and (risk_filter == "All" or item["risk"] == risk_filter)
    ]
    st.caption(f"Showing {len(filtered)} matching record(s) from the {len(scans)} most recent scans (up to 500).")
    if not filtered:
        st.info("No scans match these filters. Run a scanner or change your filters.")
    else:
        st.subheader("Recent Security Assessments")
        display = [{
            "Scan ID": s["id"], "Timestamp (UTC)": s["timestamp"],
            "Scanner": s["scan_type"], "Risk Score": s["score"],
            "Risk Level": s["risk"], "Security Findings": "; ".join(s["findings"]),
        } for s in filtered]
        st.dataframe(display, width="stretch", hide_index=True)
        st.download_button(
            "Export filtered history to CSV",
            data=_history_csv(filtered),
            file_name="sn00py_scan_history.csv",
            mime="text/csv",
            key="download_history",
        )
        st.caption("CSV exports contain your saved findings. Review them before sharing.")
